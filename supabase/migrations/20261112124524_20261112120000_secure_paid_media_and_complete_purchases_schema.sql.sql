/*
# Secure paid-media storage and complete purchases schema

## Plain-English explanation
The `paid-media` storage bucket did not exist — paid uploads were failing silently.
The `purchases` table was missing 7 columns that both the whop-webhook and
whop-payment edge functions write to (status, access_token, access_token_hash,
expires_at, claim_hash, gross_paid, status_changed_at), so every webhook upsert
was rejected by Postgres and returned a 500.

## 1. Storage — new private bucket
- `paid-media` bucket created as PRIVATE (public = false).
- Paid media files are NOT publicly readable. They are only accessible via
  time-limited signed URLs generated by edge functions using the service role key.
- Authenticated creators can INSERT (upload) and DELETE files to/in this bucket.
- No public SELECT policy exists — this is the security boundary.

## 2. Purchases table — added columns
- `status` (text, NOT NULL, default 'active') — tracks purchase lifecycle
  (active, refunded, disputed).
- `status_changed_at` (timestamptz, nullable) — when status last changed.
- `access_token` (text, nullable) — plaintext guest access token (whop-payment flow).
- `access_token_hash` (text, nullable) — SHA-256 hashed token (whop-webhook flow).
- `expires_at` (timestamptz, nullable) — access link expiry timestamp.
- `claim_hash` (text, nullable) — buyer claim hash for browser-based unlock.
- `gross_paid` (numeric, nullable) — gross amount before platform fees.

## 3. Security changes
- paid-media bucket: private (no public read).
- Storage policies: authenticated INSERT/DELETE only, no public SELECT.
- service_role bypasses RLS and can generate signed URLs in edge functions.
*/

-- ── 1. Create private paid-media bucket ──
INSERT INTO storage.buckets (id, name, public)
VALUES ('paid-media', 'paid-media', false)
ON CONFLICT (id) DO NOTHING;

-- ── 2. Storage policies for paid-media ──
-- Creators can upload to paid-media (gated by KYC + content triggers at the DB level)
DROP POLICY IF EXISTS "paid_media_insert" ON storage.objects;
CREATE POLICY "paid_media_insert"
ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (bucket_id = 'paid-media');

-- Creators can delete their own files from paid-media
DROP POLICY IF EXISTS "paid_media_delete" ON storage.objects;
CREATE POLICY "paid_media_delete"
ON storage.objects FOR DELETE
TO authenticated
USING (bucket_id = 'paid-media');

-- No SELECT policy: paid-media files are private.
-- Access is only via signed URLs generated by edge functions (service role).

-- ── 3. Add missing columns to purchases ──
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'status') THEN
    ALTER TABLE purchases ADD COLUMN status text NOT NULL DEFAULT 'active';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'status_changed_at') THEN
    ALTER TABLE purchases ADD COLUMN status_changed_at timestamptz;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'access_token') THEN
    ALTER TABLE purchases ADD COLUMN access_token text;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'access_token_hash') THEN
    ALTER TABLE purchases ADD COLUMN access_token_hash text;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'expires_at') THEN
    ALTER TABLE purchases ADD COLUMN expires_at timestamptz;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'claim_hash') THEN
    ALTER TABLE purchases ADD COLUMN claim_hash text;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_name = 'purchases' AND column_name = 'gross_paid') THEN
    ALTER TABLE purchases ADD COLUMN gross_paid numeric;
  END IF;
END $$;

-- Grant service_role access to paid-media storage (for signed URLs in edge functions)
GRANT SELECT, INSERT, UPDATE, DELETE ON storage.objects TO service_role;
